// Quita duplicados por palabra, conservando la primera definición.
const vistos = new Set();
export const PALABRAS_AHORCADO = AHORCADO_PALABRAS.filter((p) => {
  const clave = p.palabra.toLowerCase();
  if (vistos.has(clave)) return false;
  vistos.add(clave);
  return true;
});

export const palabrasPorDificultad = (nivel) =>
  PALABRAS_AHORCADO.filter((p) => p.dificultad === nivel);
